function normalizar(valor) {
  return String(valor ?? '')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function buscarTopSecret(query) {
  const termo = normalizar(query);
  if (!termo) {
    return `=== ${dossieTopSecret.metadata.titulo.toUpperCase()} ===
Autor: ${dossieTopSecret.metadata.autor} [${dossieTopSecret.metadata.classificacao}]
Pesquise por um ano, período ou nome citado no dossiê.`;
  }

  const termos = termo.split(/\s+/);
  const resultados = dossieTopSecret.registros.filter((registro) => {
    const texto = normalizar(`${registro.periodo} ${registro.titulo} ${registro.detalhe}`);
    return termos.every((palavra) => texto.includes(palavra));
  });

  if (resultados.length === 0) {
    return `Nenhum registro do dossiê encontrado para "${String(query).trim()}".`;
  }

  return `=== REGISTROS DO DOSSIÊ PARA "${String(query).trim()}" ===\n\n${resultados
    .map((registro) => `[${registro.periodo}] ${registro.titulo}\n${registro.detalhe}`)
    .join('\n\n')}`;
}

